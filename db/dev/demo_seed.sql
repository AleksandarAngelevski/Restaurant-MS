-- ---------------------------------------------------------------------------
-- Order history: 80 closed orders over the last 14 days, driven through the
-- stored procedures so invoices, stock and the usage log are consistent.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    v_waiters INT4[];
    v_cooks INT4[];
    v_members RECORD;
    v_order_id INT4;
    v_ts TIMESTAMP;
    v_last_log INT4;
    v_type INT4;
    v_table INT4;
    i INT4;
    j INT4;
BEGIN
    PERFORM setseed(0.42);

    SELECT array_agg(e.Id ORDER BY e.Id) INTO v_waiters
    FROM Employee e
    JOIN EmployeeRole er ON er.EmployeeId = e.Id
    JOIN EmployeeType et ON et.Id = er.EmployeeTypeid
    WHERE et.Type = 'Waiter' AND e.DateResignation IS NULL;

    SELECT array_agg(e.Id ORDER BY e.Id) INTO v_cooks
    FROM Employee e
    JOIN EmployeeRole er ON er.EmployeeId = e.Id
    JOIN EmployeeType et ON et.Id = er.EmployeeTypeid
    WHERE et.Type = 'Kitchen';

    FOR i IN 1..80 LOOP
        v_ts := date_trunc('day', now()) - make_interval(days => 1 + (random() * 13)::INT)
                + make_interval(hours => 9 + (random() * 12)::INT, mins => (random() * 59)::INT);
        v_type := 1 + (random() * 3)::INT;
        v_table := CASE WHEN v_type = 1 THEN 1 + (random() * 19)::INT ELSE NULL END;
        v_last_log := COALESCE((SELECT MAX(Id) FROM ProductUsageLog), 0);

        CALL sp_create_order(v_waiters[1 + (random() * (array_length(v_waiters, 1) - 1))::INT],
                             v_type, v_table, v_order_id);

        FOR j IN 1..(1 + (random() * 3)::INT) LOOP
            SELECT mm.Id, mm.MenuItemId INTO v_members
            FROM MenuMember mm
            JOIN Menu m ON m.Id = mm.MenuId
            WHERE m.Active
            ORDER BY random()
            LIMIT 1;

            CALL sp_add_order_item(v_order_id, v_members.Id, v_members.MenuItemId,
                                   1 + (random() * 2)::INT, NULL);
        END LOOP;

        UPDATE OrderItem
        SET Finished = TRUE,
            CreatedBy = v_cooks[1 + (random() * (array_length(v_cooks, 1) - 1))::INT]
        WHERE OrderId = v_order_id;

        CALL sp_close_order_and_invoice(v_order_id);

        -- backdate so the analytics dashboard has a history to show
        UPDATE "Order"
        SET DateCreated = v_ts, DateFinished = v_ts + INTERVAL '50 minutes'
        WHERE Id = v_order_id;
        UPDATE Invoice SET InvoiceDate = v_ts + INTERVAL '50 minutes' WHERE OrderId = v_order_id;
        UPDATE ProductUsageLog SET Timestamp = v_ts + INTERVAL '20 minutes' WHERE Id > v_last_log;
    END LOOP;
END;
$$;

